// Group by territory for quick access
export function getPracticesForTerritory(territoryId, level = null) {
  return WEATHER_PRACTICES.filter(p =>
    p.territories.includes(territoryId) &&
    (level === null || p.level === level)
  )
}

// Get a short featured practice per level for a territory
export function getFeaturedPractices(territoryId) {
  const levels = ['L1', 'L2', 'L3']
  return levels.map(level => {
    const matches = getPracticesForTerritory(territoryId, level)
    return matches.length > 0 ? matches[0] : null
  }).filter(Boolean)
}
